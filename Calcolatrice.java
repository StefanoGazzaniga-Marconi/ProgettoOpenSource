public class Calcolatrice {
    
    // Un metodo semplicissimo per sommare due numeri
    public int somma(int a, int b) {
        return a + b;
    }

	public int sottrazioneee(int a, int b){
	return a-b;}

    public double divisione( int a,int b){
        return a/b;
    }
    //una funzione per la moltiplicazione
    public double moltiplicazione(double a, double b){
        return a*b;
    }
}
